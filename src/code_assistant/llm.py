"""LLM interface: a streaming protocol, an offline template LLM, OpenAI stub.

Streaming matters for a code assistant: users watch code appear token by
token and can abort early, which is a latency / UX win over waiting for a
full completion. Every backend here therefore exposes both ``generate``
(full string) and ``stream`` (iterator of chunks).

:class:`TemplateLLM` is deterministic and fully offline — it recognises a
small, explicit spec format so the demo, the CLI, and the tests run with
no API keys and no network:

* generate — if the prompt names a signature like ```add(a, b)``` and a
  behaviour keyword (sum / product / reverse / uppercase …), it emits that
  function; otherwise it emits a documented identity function.
* refactor — it returns the original code with a docstring added to any
  undocumented function (a real, mechanical, safe refactor).
* explain — it returns a short deterministic explanation.
"""

from __future__ import annotations

import ast
import os
import re
from collections.abc import Iterator
from typing import Protocol, runtime_checkable


@runtime_checkable
class LLM(Protocol):
    """Any backend that can generate code, streaming or whole."""

    def generate(self, prompt: str) -> str:
        """Return the complete response for ``prompt``."""
        ...

    def stream(self, prompt: str) -> Iterator[str]:
        """Yield the response for ``prompt`` in chunks."""
        ...


_BEHAVIOURS: list[tuple[tuple[str, ...], str]] = [
    (("sum", "add", "addition"), "{a} + {b}"),
    (("product", "multiply", "multiplication"), "{a} * {b}"),
    (("difference", "subtract", "subtraction"), "{a} - {b}"),
    (("quotient", "divide", "division"), "{a} / {b}"),
]


def _find_signature(prompt: str) -> tuple[str, list[str]] | None:
    match = re.search(r"`([a-zA-Z_][a-zA-Z0-9_]*)\(([^)]*)\)`", prompt)
    if not match:
        match = re.search(r"def\s+([a-zA-Z_][a-zA-Z0-9_]*)\(([^)]*)\)", prompt)
    if not match:
        return None
    args = [a.strip().split("=")[0].split(":")[0].strip()
            for a in match.group(2).split(",") if a.strip()]
    return match.group(1), args


def _generate_code(prompt: str) -> str:
    lower = prompt.lower()
    found = _find_signature(prompt)
    if found is None:
        return (
            'def generated_function(x):\n'
            '    """Return the input unchanged (offline template default)."""\n'
            "    return x\n"
        )
    name, args = found
    params = ", ".join(args) if args else "x"
    body = None
    if len(args) >= 2:
        for keywords, template in _BEHAVIOURS:
            if any(kw in lower for kw in keywords):
                body = template.format(a=args[0], b=args[1])
                break
    if body is None and "reverse" in lower and args:
        body = f"{args[0]}[::-1]"
    if body is None and "uppercase" in lower and args:
        body = f"str({args[0]}).upper()"
    if body is None and "lowercase" in lower and args:
        body = f"str({args[0]}).lower()"
    if body is None:
        body = args[0] if args else "None"
    return (
        f"def {name}({params}):\n"
        f'    """Generated by TemplateLLM for: {name}({params})."""\n'
        f"    return {body}\n"
    )


def _add_missing_docstrings(code: str) -> str:
    """Mechanical safe refactor: document undocumented functions."""
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return code
    lines = code.splitlines()
    # Insert from the bottom up so line numbers stay valid.
    targets = [
        node for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        and ast.get_docstring(node) is None
    ]
    for node in sorted(targets, key=lambda n: n.lineno, reverse=True):
        indent = " " * (node.col_offset + 4)
        doc = f'{indent}"""TODO: document {node.name}."""'
        lines.insert(node.lineno, doc)  # body starts right after def line
    return "\n".join(lines) + ("\n" if code.endswith("\n") or lines else "")


def _refactor_code(prompt: str) -> str:
    match = re.search(r"```python\n(.*?)```", prompt, re.DOTALL)
    original = match.group(1).strip("\n") if match else ""
    if not original:
        return _generate_code(prompt)
    return _add_missing_docstrings(original)


def _explain_code(prompt: str) -> str:
    match = re.search(r"```python\n(.*?)```", prompt, re.DOTALL)
    code = match.group(1) if match else ""
    names = []
    try:
        for node in ast.walk(ast.parse(code)):
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                names.append(node.name)
    except SyntaxError:
        pass
    subject = ", ".join(names) if names else "the snippet"
    return (
        f"This code defines {subject}. It is written in Python, uses only "
        "the constructs visible in the snippet, and can be checked with "
        "the validator and test harness in this project."
    )


class TemplateLLM:
    """Deterministic, offline LLM stand-in (no keys, no network)."""

    name = "template-llm"

    def generate(self, prompt: str) -> str:
        """Return a complete deterministic response for ``prompt``."""
        if "TASK_TYPE: refactor" in prompt:
            return _refactor_code(prompt)
        if "TASK_TYPE: explain" in prompt:
            return _explain_code(prompt)
        return _generate_code(prompt)

    def stream(self, prompt: str) -> Iterator[str]:
        """Yield the full response line-by-line (the streaming interface)."""
        for line in self.generate(prompt).splitlines(keepends=True):
            yield line


class OpenAILLM:
    """OpenAI-backed LLM — lazy import, never required by the core.

    Raises:
        ImportError: If the ``openai`` package is not installed.
        RuntimeError: If ``OPENAI_API_KEY`` is not set.
    """

    name = "openai"

    def __init__(self, model: str = "gpt-4o-mini") -> None:
        try:
            import openai  # noqa: F401  (lazy: optional dependency)
        except ImportError as exc:  # pragma: no cover - optional dep
            raise ImportError(
                "OpenAILLM needs the optional 'openai' package: "
                'pip install -e ".[openai]"'
            ) from exc
        if not os.environ.get("OPENAI_API_KEY"):
            raise RuntimeError("OPENAI_API_KEY is not set")
        self.model = model

    def generate(self, prompt: str) -> str:  # pragma: no cover - network
        """Return a completion from the OpenAI API."""
        from openai import OpenAI

        client = OpenAI()
        response = client.chat.completions.create(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
        )
        return response.choices[0].message.content or ""

    def stream(self, prompt: str) -> Iterator[str]:  # pragma: no cover
        """Yield a completion from the OpenAI API in streaming chunks."""
        from openai import OpenAI

        client = OpenAI()
        with client.chat.completions.create(
            model=self.model, messages=[{"role": "user", "content": prompt}],
            stream=True,
        ) as stream:
            for chunk in stream:
                delta = chunk.choices[0].delta.content
                if delta:
                    yield delta
